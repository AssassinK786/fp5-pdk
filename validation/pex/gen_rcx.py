#!/usr/bin/env python3
"""Generate fp5A.rcx: an OpenRCX rules deck calibrated to FP5A's 3-metal stack.

Row grammar (OpenROAD src/rcx/src/extRCmodel.cpp):
  cap tables (OVER/UNDER/OVERUNDER):  sep_um  coupling  fringe  res
      col0 sep = same-layer neighbour spacing (um); col1 lateral coupling;
      col2 ground/fringe cap to the named context; col3 resistance.
  RESOVER:                            dist1_um  dist2_um  0  res
      two neighbour spacings, resistance only.
  DIAGUNDER:                          sep_um  0  diag_cap  0
      diagonal-context cap lives in the fringe column.
Units: ALL cap/res values are PER NANOMETRE of wire (fF/nm, ohm/nm) --
extDistRC::readRC divides by dbFactor (DBU/um * 0.001 = 1 nm at 1000 DBU/um)
and addRC multiplies by length in DBU.  wire_rc.txt is per um => /1000.

Section structure mirrors sky130hs rcx_patterns.rules: one WIDTH Table entry
per metal, RESOVER for every context below the metal (0=sub/poly), OVER for
every context below, UNDER/DIAGUNDER for every context above, OVERUNDER for
every (below, above) pair.  Context numbers: 0 substrate/poly, 1..3 metals.

Physics source: tech/wire_rc.txt (MOSIS T89Y medians).
    Rsh      : m1 0.09, m2 0.09, m3 0.05 ohm/sq
    area cap : m1 28, m2 12, m3 8 aF/um^2 to substrate
    fringe   : m1 52, m2 33, m3 26 aF/um (per edge, to substrate)
    interlayer area cap: M1/poly 63, M2/M1 31, M3/M2 31 aF/um^2
    interlayer fringe  : 58 / 33 / 56 aF/um
    min width: m1/m2 0.9 um, m3 1.5 um

Coupling falloff is a w/(w+sep) analytic model -- estimates, not field-solved.
Isolated-wire ground C and sheet R match wire_rc.txt exactly.
"""
import os

OUT = os.path.join(os.path.dirname(__file__), "..", "..",
                   "fp5A", "libs.tech", "klayout", "pex", "fp5A.rcx")

RSH    = {1: 0.09, 2: 0.09, 3: 0.05}
AREA   = {1: 28.0, 2: 12.0, 3: 8.0}          # aF/um^2 to substrate
FRINGE = {1: 52.0, 2: 33.0, 3: 26.0}         # aF/um per edge, to substrate
XAREA  = {(1, 0): 63.0, (2, 1): 31.0, (3, 2): 31.0}   # aF/um^2 (upper, lower)
XFRINGE= {(1, 0): 58.0, (2, 1): 33.0, (3, 2): 56.0}   # aF/um
MINW   = {1: 0.9, 2: 0.9, 3: 1.5}            # um -- one width per table
# separations (um); first entry >= min spacing so sep>0 like the sky130 tables
SEPS   = [0.9, 1.2, 1.5, 2.0, 2.7, 3.6, 4.8, 6.0, 9.0, 15.0, 30.0]

PER_NM = 1e-3

def ctx_caps(n, ctx):
    """(area_aF/um^2, fringe_aF/um) describing wire on metal n against context
    plane ctx.  ctx == 0 means substrate/poly."""
    if ctx == 0:
        return AREA[n], FRINGE[n]
    key = (n, ctx) if n > ctx else (ctx, n)
    return XAREA.get(key, AREA[n]), XFRINGE.get(key, FRINGE[n])

def lat_coupling(w, s, ca_af, cf_af):
    c0 = (ca_af * w + 2.0 * cf_af) / 1000.0          # fF/um at s=0
    return c0 * (w / (w + max(s, 1e-9)))

def ground_fringe(w, ca_af, cf_af, lateral_fF):
    g = (ca_af * w + 2.0 * cf_af) / 1000.0 - lateral_fF
    return max(g, 0.0)

def res_nm(met, w):
    return RSH[met] / w * PER_NM                      # ohm/nm

def cap_table(w, met, ctx):
    ca, cf = ctx_caps(met, ctx)
    rows = [f"DIST count {len(SEPS)} width {w:g}"]
    for s in SEPS:
        cc = lat_coupling(w, s, ca, cf)
        fr = ground_fringe(w, ca, cf, cc)
        rows.append(f"{s:g} {cc*PER_NM:.6g} {fr*PER_NM:.6g} {res_nm(met,w):.6g}")
    rows.append("END DIST")
    return "\n".join(rows)

def resover_table(w, met):
    # 2-D grid of (left-neighbour-dist, right-neighbour-dist, 0, res).
    # Resistance is spacing-independent here, so every grid point = res.
    ds = SEPS + [w]                       # include width as a valid first dist
    rows = [f"DIST count {len(ds)*(len(ds))//2} width {w:g}"]
    cnt = 0
    for i, d1 in enumerate(ds):
        for d2 in ds[i:]:
            rows.append(f"{d1:g} {d2:g} 0 {res_nm(met, w):.6g}")
            cnt += 1
    rows[0] = f"DIST count {cnt} width {w:g}"
    rows.append("END DIST")
    return "\n".join(rows)

def diag_table(w, met, ctx):
    ca, cf = ctx_caps(met, ctx)
    rows = [f"DIST count {len(SEPS)} width {w:g}"]
    for s in SEPS:
        diag = lat_coupling(w, s, ca, cf) * 0.6 * PER_NM   # estimate
        rows.append(f"{s:g} 0 {diag:.6g} 0")
    rows.append("END DIST")
    return "\n".join(rows)

def empty_dist(w):
    return f"DIST count 0 width {w:g}\nEND DIST"

def main():
    out = [
        "* FP5A OpenRCX deck, calibrated to MOSIS T89Y 3-metal data.",
        "* Generated by validation/pex/gen_rcx.py -- do not hand-edit tables.",
        "* cap rows: sep_um  coupling_fF/nm  fringe_fF/nm  res_ohm/nm.",
        "* RESOVER rows: dist1_um dist2_um 0 res_ohm/nm; DIAGUNDER: sep 0 diag 0.",
        "* Coupling falloff = w/(w+sep) analytic model (estimates).",
        "Extraction Rules for OpenRCX",
        "",
        "DIAGMODEL ON",
        "",
        "LayerCount 3",
        "DensityRate 1  0",
        "",
        "DensityModel 0",
    ]
    for n in (1, 2, 3):
        w = MINW[n]
        # ---- RESOVER: one section per context below (0..n-1) ----
        out += ["", f"Metal {n} RESOVER", f"WIDTH Table 1 entries:  {w:g}", ""]
        for ctx in range(0, n):
            out += [f"Metal {n} RESOVER {ctx}", resover_table(w, n)]
        # ---- OVER: every context below (0..n-1) ----
        out += ["", f"Metal {n} OVER", f"WIDTH Table 1 entries:  {w:g}", ""]
        for ctx in range(0, n):
            out += [f"Metal {n} OVER {ctx}", cap_table(w, n, ctx)]
        # ---- UNDER: every context above (n+1..3); top metal: 0 widths ----
        above = list(range(n + 1, 4))
        out += ["", f"Metal {n} UNDER"]
        if above:
            out += [f"WIDTH Table 1 entries:  {w:g}", ""]
            for ctx in above:
                out += [f"Metal {n} UNDER {ctx}", cap_table(w, n, ctx)]
        else:
            out += ["WIDTH Table 0 entries: ", ""]
        # ---- DIAGUNDER ----
        out += ["", f"Metal {n} DIAGUNDER"]
        if above:
            out += [f"WIDTH Table 1 entries:  {w:g}", ""]
            for ctx in above:
                out += [f"Metal {n} DIAGUNDER {ctx}", diag_table(w, n, ctx)]
        else:
            out += ["WIDTH Table 0 entries: ", ""]
        # ---- OVERUNDER: only metals with both a below- and above-context ----
        # valid pairs: the wire's own OVER context is the metal below (n-1),
        # and UNDER context n+1.  Other combos aren't emitted for a 3-metal
        # stack (matches sky130: only 'Metal 2 OVER 1 UNDER 3').
        if n == 2:
            out += ["", f"Metal {n} OVERUNDER", f"WIDTH Table 1 entries:  {w:g}", ""]
            out += [f"Metal {n} OVER {n-1} UNDER {n+1}", cap_table(w, n, n - 1)]
    out += ["", "END DensityModel 0", ""]

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, "w").write("\n".join(out))
    print(f"wrote {OUT}")

    print("\nself-check (isolated wire: C = area*w + 2*fringe, R = Rsh/w):")
    for n in (1, 2, 3):
        w = MINW[n]
        c = (AREA[n] * w + 2 * FRINGE[n])
        print(f"  m{n} w={w}: C {c:.0f} aF/um (wire_rc {c:.0f})  "
              f"R {RSH[n]/w:.3f} ohm/um")

if __name__ == "__main__":
    main()
